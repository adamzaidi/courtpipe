"""Aggregate progress page for the motion-to-dismiss data collection.

Built from the fetch state (run history, search progress) and the scored report's
funnel. Counts only: no docket, case, party or judge appears, and no test metric is
printed, since nothing is a result until the cohort is complete and the audit is done.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

EDU_HOURLY_LIMIT = 5000

# Motion-level steps, in the order cohort.build_rows applies them.
MOTION_STEPS = [
    ("outside_window", "Filed outside the 2016-2023 study window", "by design"),
    ("unresolved", "No order on the docket after the motion yet", "by design"),
    ("order_text_unclear", "First later order's docket text does not say granted or denied", "fixable: read the order's PDF text"),
    ("link_ambiguous", "Order cannot be tied to one motion (no or several document numbers)", "fixable: drop briefs counted as motions"),
    ("first_order_rules_on_other_motion", "First later order rules on a different motion", "fixable: look past the first order"),
]
LINKED_STEPS = [
    ("movant_unknown", "Movant cannot be identified"),
    ("not_corporate_defendant", "Movant is not a corporate defendant"),
    ("label_unclear", "Outcome wording unclear"),
]


def _n(value: Any) -> str:
    return f"{value:,}" if isinstance(value, (int, float)) else "-"


def build_progress(state: dict[str, Any], report: Optional[dict[str, Any]] = None) -> str:
    runs = list(state.get("runs") or [])
    queries = dict(state.get("queries") or {})
    done = sum(1 for q in queries.values() if q.get("exhausted") and not q.get("pending"))
    large = len(state.get("large") or [])
    last = runs[-1] if runs else {}
    total_requests = sum(int(r.get("requests") or 0) for r in runs)
    funnel = (report or {}).get("funnel") or {}

    lines = [
        "# Motion-to-dismiss data collection: progress",
        "",
        "This page is generated by `courtpipe mtd-progress` after each collection run. "
        "It shows counts only. No case, party or judge is named here, and no model scores "
        "are shown: none count as results until collection is complete and the hand audit "
        "is done (see [SPEC.md](SPEC.md)).",
        "",
        "## Why the API volume",
        "",
        "The study asks whether a motion to dismiss filed by a corporate defendant in federal "
        "court can be predicted from what was on the docket before the ruling. Answering that "
        "needs every docket in the cohort (four nature-of-suit codes, 2014-2023 filings that "
        "mention a motion to dismiss), each with its full entry history and filing text, "
        "because the ruling has to be matched to the motion and labeled from the court's own "
        "words. That is many requests per docket. Collection runs on a schedule at 3,000 "
        f"requests an hour, below the {EDU_HOURLY_LIMIT:,}/hour limit on the project's "
        "CourtListener education membership, and every response is cached so nothing is "
        "fetched twice.",
        "",
        "## Status",
        "",
        "| | |",
        "| --- | ---: |",
        f"| Dockets collected | {_n(last.get('total_dockets'))} |",
        f"| Large dockets waiting (collected over several runs) | {_n(large)} |",
        f"| Searches finished | {done} of {len(queries)} |",
        f"| Collection runs | {len(runs)} |",
        f"| API requests to date | {_n(total_requests)} |",
        f"| Collection complete | {'yes' if queries and done == len(queries) and not large else 'no'} |",
        "",
    ]

    if runs:
        lines += [
            "## Runs",
            "",
            "| # | Finished (UTC) | Hours | Requests | New dockets | Total dockets | Transient failures | Stopped because |",
            "| ---: | --- | ---: | ---: | ---: | ---: | ---: | --- |",
        ]
        for i, r in enumerate(runs, 1):
            hours = f"{r['minutes'] / 60:.1f}" if r.get("minutes") is not None else "-"
            lines.append(
                f"| {i} | {r.get('finished', '-')} | {hours} | {_n(r.get('requests'))} | "
                f"{_n(r.get('new_dockets'))} | {_n(r.get('total_dockets'))} | "
                f"{_n(r.get('transient_failures'))} | {r.get('stop', '-')} |"
            )
        first = runs[0]
        before = int(first.get("total_dockets") or 0) - int(first.get("new_dockets") or 0)
        if before > 0:
            lines.append(f"\n{_n(before)} dockets were collected before run 1's record was kept (a run that crashed before saving its run record).")
        if any(r.get("finished") is None for r in runs):
            lines.append("\nRuns before 22 November 2026 did not record their finish time or length.")
        lines.append("")

    if funnel:
        entries = int(funnel.get("mtd_motion_entries") or 0)
        lines += [
            "## From dockets to a labeled cohort",
            "",
            f"Across {_n(funnel.get('dockets_in_scope'))} dockets in scope, the pipeline found "
            f"{_n(entries)} docket entries that read as motions to dismiss. Each is matched to "
            "the order that ruled on it, then labeled. Where each one ends up:",
            "",
            "| Step | Motions | Share | Note |",
            "| --- | ---: | ---: | --- |",
        ]
        accounted = 0
        for key, label, note in MOTION_STEPS:
            v = int(funnel.get(key) or 0)
            accounted += v
            lines.append(f"| {label} | {_n(v)} | {v / entries:.0%} | {note} |" if entries else f"| {label} | {_n(v)} | - | {note} |")
        linked = int(funnel.get("linked_to_order") or 0)
        accounted += linked
        lines.append(f"| **Matched to its ruling** | **{_n(linked)}** | **{linked / entries:.0%}** | |" if entries else "")
        other = entries - accounted
        if other:
            lines.append(f"| Other (no usable filing date, or not counted by an older pipeline version) | {_n(other)} | {other / entries:.0%} | |")
        lines += ["", "Of the matched motions:", "", "| Step | Motions |", "| --- | ---: |"]
        for key, label in LINKED_STEPS:
            lines.append(f"| {label} | {_n(funnel.get(key))} |")
        lines.append(f"| **Labeled cohort (granted, granted in part, denied)** | **{_n(funnel.get('labeled_cohort'))}** |")
        briefs = funnel.get("motion_entries_look_like_briefs")
        if briefs:
            lines += [
                "",
                f"Known issue: {_n(briefs)} of the {_n(entries)} entries counted as motions open "
                "with \"response\", \"reply\", \"memorandum\", \"opposition\" or \"brief\". They "
                "are briefs about a motion, not motions, and they make orders look ambiguous. "
                "Fixes to the matching step are tracked in [ROADMAP.md](../../ROADMAP.md).",
            ]
        lines.append("")

    if report:
        gate = report.get("modeling_gate") or {}
        lines += [
            "## Scoring",
            "",
            "Every run re-scores the cohort end to end. Scores stay provisional until collection "
            "is complete and the two-reader audit passes, so they are not shown here.",
            "",
            f"- Labeled motions: {_n(funnel.get('labeled_cohort'))} "
            f"(train {_n((report.get('split') or {}).get('train_rows'))}, "
            f"test {_n((report.get('split') or {}).get('test_rows'))})",
            f"- Audit gate: {report.get('audit_gate', '-')}",
            f"- Modeling gate: {'pass' if gate.get('passed') else 'not yet met'}",
            "",
        ]
    return "\n".join(lines)


def write_progress(state_path: Path, report_path: Optional[Path], out_path: Path) -> Path:
    state = json.loads(Path(state_path).read_text())
    report = None
    if report_path and Path(report_path).exists():
        report = json.loads(Path(report_path).read_text())
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_progress(state, report))
    return out_path
