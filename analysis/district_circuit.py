EXCLUDED_DISTRICT_PARENT = "usdistct"


def circuit_for_district(court_id: str | None) -> str:
    if not court_id:
        return "unknown"
    key = str(court_id).strip().lower()
    if key == EXCLUDED_DISTRICT_PARENT:
        return "excluded_parent"
    return DISTRICT_TO_CIRCUIT.get(key, "unknown")
